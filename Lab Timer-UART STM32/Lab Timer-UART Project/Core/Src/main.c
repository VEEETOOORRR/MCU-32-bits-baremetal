/* USER CODE BEGIN 4 */
void Gerar_LUT_Senoide(void) {
    float amplitude = PWM_ARR / 2.0f;
    for (int i = 0; i < LUT_SIZE; i++) {
        float valor = amplitude * (1.0f + sinf(2.0f * (float)M_PI * i / LUT_SIZE));
        lut_senoide[i] = (uint16_t)(valor + 0.5f);
    }
}

void Set_Frequencia_Senoide(float freq_hz) {
    // Calcula o passo do acumulador de 32 bits: M = (freq * 2^32) / F_PWM
    tuning_word = (uint32_t)((freq_hz * 4294967296.0f) / F_PWM);
}

// Esta função é chamada automaticamente a cada 25 us (40 kHz) pelo hardware
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) {
    if (htim->Instance == TIM3) {
        phase_acc += tuning_word;

        // Como LUT_SIZE = 1024 (2^10), pegamos os 10 bits mais altos (32 - 10 = 22)
        uint16_t index = phase_acc >> 22;

        TIM3->CCR1 = lut_senoide[index];
    }
}

// Interrupção da UART1 - Chamada a cada caractere recebido
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
  if (huart->Instance == USART1) {
    if (rx_byte == '\r' || rx_byte == '\n') {
      if (rx_index > 0) {
        rx_buffer[rx_index] = '\0';
        rx_index = 0;
        nova_freq_pronta = 1;
      }
    }
    else if (rx_index < (UART_BUF_SIZE - 1)) {
      if (rx_byte == ',') rx_byte = '.';
      rx_buffer[rx_index++] = (char)rx_byte;
    }

    // Reativa a escuta do próximo byte
    HAL_UART_Receive_IT(&huart1, &rx_byte, 1);
  }
}
